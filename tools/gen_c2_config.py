#!/usr/bin/env python3
"""
gen_c2_config.py — generates masked byte arrays for native-lib.cpp

Takes a C2 URL + API key and produces the XOR-masked constants that
NativeKey.c2Url() / NativeKey.apiKey() decode at runtime.

Masking scheme matches native-lib.cpp unmask():
    out[i] = in[i] ^ (seed + i)
"""
import sys
import re

SEED_URL1 = 0x5A
SEED_URL2 = 0xA5
SEED_KEY = 0x33


def mask(data: bytes, seed: int) -> bytes:
    return bytes(b ^ ((seed + i) & 0xFF) for i, b in enumerate(data))


def fmt(name: str, data: bytes) -> str:
    body = ", ".join(f"0x{b:02X}" for b in data)
    # wrap at 16 bytes per line
    chunks = [body[i:i + 16 * 6] for i in range(0, len(body), 16 * 6)]
    out = f"static const uint8_t {name}[] = {{"
    for idx, c in enumerate(chunks):
        sep = "," if idx < len(chunks) - 1 else ""
        out += f"\n    {c}{sep}"
    out += "};"
    return out


def main():
    if len(sys.argv) != 3:
        print(f"Usage: {sys.argv[0]} <c2_url> <api_key>")
        print("Example: gen_c2_config.py https://myapp.onrender.com sk-xt-abc123")
        sys.exit(1)

    url = sys.argv[1].rstrip("/")
    api_key = sys.argv[2]

    half = (len(url) + 1) // 2
    u1, u2 = url[:half].encode("utf-8"), url[half:].encode("utf-8")

    print("// Auto-generated by tools/gen_c2_config.py — do not edit by hand")
    print(f"// C2: {url}")
    print()
    print(fmt("U1", mask(u1, SEED_URL1)))
    print(fmt("U2", mask(u2, SEED_URL2)))
    print(fmt("AK", mask(api_key.encode("utf-8"), SEED_KEY)))
    print()
    print("// Copy the 4 blocks above into native-lib.cpp")


if __name__ == "__main__":
    main()
