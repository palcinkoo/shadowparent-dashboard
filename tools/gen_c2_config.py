#!/usr/bin/env python3
"""
gen_c2_config.py — generates masked byte arrays for native-lib.cpp

Takes a C2 URL + API key and produces the XOR-masked constants that
NativeKey.c2Url() / NativeKey.apiKey() decode at runtime.

Masking scheme matches native-lib.cpp unmask():
    out[i] = in[i] ^ (seed + i)
"""
import sys
import re

SEED_URL1 = 0x5A
SEED_URL2 = 0xA5
SEED_KEY = 0x33


def mask(data: bytes, seed: int) -> bytes:
    return bytes(b ^ ((seed + i) & 0xFF) for i, b in enumerate(data))


def fmt(name: str, data: bytes) -> str:
    lines = []
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in chunk))
    body = ",\n".join(lines)
    return f"static const uint8_t {name}[] = {{\n{body}\n}};"


NATIVE_CPP = "android/app/src/main/cpp/native-lib.cpp"


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    write = "--write" in sys.argv
    if len(args) != 2:
        print(f"Usage: {sys.argv[0]} <c2_url> <api_key> [--write]")
        print("Example: gen_c2_config.py https://myapp.onrender.com sk-xt-abc123 --write")
        sys.exit(1)

    url = args[0].rstrip("/")
    api_key = args[1]

    half = (len(url) + 1) // 2
    u1, u2 = url[:half].encode("utf-8"), url[half:].encode("utf-8")

    blocks = {
        "U1": fmt("U1", mask(u1, SEED_URL1)),
        "U2": fmt("U2", mask(u2, SEED_URL2)),
        "AK": fmt("AK", mask(api_key.encode("utf-8"), SEED_KEY)),
    }
    header = f"// Auto-generated by tools/gen_c2_config.py — do not edit by hand\n// C2: {url}\n"

    if write:
        cpp = open(NATIVE_CPP).read()
        for name, block in blocks.items():
            cpp = re.sub(
                r"static const uint8_t " + name + r"\[\] = \{.*?\};",
                block.replace("\\", "\\\\"),
                cpp,
                flags=re.S,
            )
        cpp = re.sub(
            r"// Auto-generated by tools/gen_c2_config\.py[^\n]*\n// C2: [^\n]*\n",
            header,
            cpp,
        )
        open(NATIVE_CPP, "w").write(cpp)
        print(f"[+] {NATIVE_CPP} updated for {url}")
        return

    print(header)
    for block in blocks.values():
        print(block)
    print()
    print("// Copy the 3 blocks above into native-lib.cpp")


if __name__ == "__main__":
    main()
